// PostgreSQL connection tester, schema migration, and data exporter

require('./env');
const net = require('node:net');
const path = require('node:path');
const fs = require('node:fs');
const db = require('./db');

const PG_CONFIG = {
  host: process.env.PG_HOST || '127.0.0.1',
  port: parseInt(process.env.PG_PORT || '5432', 10),
  user: process.env.PG_USER || 'postgres',
  database: process.env.PG_DATABASE || 'mlic_challenge',
  password: process.env.PG_PASSWORD || 'postgres'
};

function checkPostgresConnection(host = PG_CONFIG.host, port = PG_CONFIG.port, timeout = 1500) {
  return new Promise((resolve) => {
    const socket = new net.Socket();
    let isConnected = false;

    socket.setTimeout(timeout);

    socket.on('connect', () => {
      isConnected = true;
      socket.destroy();
      resolve({ online: true, message: `Connected to PostgreSQL on ${host}:${port}` });
    });

    socket.on('timeout', () => {
      socket.destroy();
      resolve({ online: false, message: `Connection timeout to ${host}:${port}` });
    });

    socket.on('error', (err) => {
      resolve({ online: false, message: `PostgreSQL is not responding: ${err.message}` });
    });

    socket.connect(port, host);
  });
}

async function exportToPostgresSQL() {
  const schemaPath = path.join(__dirname, '..', 'database', 'init_postgres.sql');
  const schemaSQL = fs.readFileSync(schemaPath, 'utf8');

  let exportSQL = `-- PostgreSQL Data Export Generated by MLIC CHALLENGE
-- Timestamp: ${new Date().toISOString()}

${schemaSQL}

-- Insert Users
`;

  const users = await db.all('SELECT * FROM users');
  for (const u of users) {
    exportSQL += `INSERT INTO users (id, name, email, password_hash, role, organization, bio, is_approved, created_at)
VALUES (${escapeSQL(u.id)}, ${escapeSQL(u.name)}, ${escapeSQL(u.email)}, ${escapeSQL(u.password_hash)}, ${escapeSQL(u.role)}, ${escapeSQL(u.organization)}, ${escapeSQL(u.bio)}, ${u.is_approved === 1 || u.is_approved === true ? 1 : 0}, ${escapeSQL(u.created_at)})
ON CONFLICT (id) DO UPDATE SET name = EXCLUDED.name, email = EXCLUDED.email, role = EXCLUDED.role, is_approved = EXCLUDED.is_approved;\n`;
  }

  exportSQL += '\n-- Insert Challenges\n';
  const challenges = await db.all('SELECT * FROM challenges');
  for (const c of challenges) {
    exportSQL += `INSERT INTO challenges (id, title, category, summary, problem_statement, expected_outcomes, target_sectors, reward_or_grant, author_id, is_active, created_at)
VALUES (${escapeSQL(c.id)}, ${escapeSQL(c.title)}, ${escapeSQL(c.category)}, ${escapeSQL(c.summary)}, ${escapeSQL(c.problem_statement)}, ${escapeSQL(c.expected_outcomes)}, ${escapeSQL(c.target_sectors)}, ${escapeSQL(c.reward_or_grant)}, ${escapeSQL(c.author_id)}, ${c.is_active === 1 ? 1 : 0}, ${escapeSQL(c.created_at)})
ON CONFLICT (id) DO UPDATE SET title = EXCLUDED.title;\n`;
  }

  exportSQL += '\n-- Insert Submissions\n';
  const submissions = await db.all('SELECT * FROM submissions');
  for (const s of submissions) {
    exportSQL += `INSERT INTO submissions (id, challenge_id, user_id, author_name, title, pitch, team_name, team_members, target_audience, swot, feasibility, document_path, document_name, document_size, status, likes_count, created_at, updated_at)
VALUES (${escapeSQL(s.id)}, ${escapeSQL(s.challenge_id)}, ${escapeSQL(s.user_id)}, ${escapeSQL(s.author_name)}, ${escapeSQL(s.title)}, ${escapeSQL(s.pitch)}, ${escapeSQL(s.team_name)}, ${escapeSQL(s.team_members)}, ${escapeSQL(s.target_audience)}::jsonb, ${escapeSQL(s.swot)}::jsonb, ${escapeSQL(s.feasibility)}::jsonb, ${escapeSQL(s.document_path || '')}, ${escapeSQL(s.document_name || '')}, ${s.document_size || 0}, ${escapeSQL(s.status)}, ${s.likes_count || 0}, ${escapeSQL(s.created_at)}, ${escapeSQL(s.updated_at)})
ON CONFLICT (id) DO UPDATE SET title = EXCLUDED.title, status = EXCLUDED.status;\n`;
  }

  exportSQL += '\n-- Insert Evaluations\n';
  const evaluations = await db.all('SELECT * FROM evaluations');
  for (const e of evaluations) {
    exportSQL += `INSERT INTO evaluations (id, submission_id, judge_id, judge_name, score_problem_audience, score_swot, score_feasibility_tech, score_feasibility_financial, score_innovation, total_score, feedback, strengths_observed, recommendations, created_at)
VALUES (${escapeSQL(e.id)}, ${escapeSQL(e.submission_id)}, ${escapeSQL(e.judge_id)}, ${escapeSQL(e.judge_name)}, ${e.score_problem_audience}, ${e.score_swot}, ${e.score_feasibility_tech}, ${e.score_feasibility_financial}, ${e.score_innovation}, ${e.total_score}, ${escapeSQL(e.feedback)}, ${escapeSQL(e.strengths_observed)}, ${escapeSQL(e.recommendations)}, ${escapeSQL(e.created_at)})
ON CONFLICT (id) DO UPDATE SET total_score = EXCLUDED.total_score;\n`;
  }

  return exportSQL;
}

function escapeSQL(val) {
  if (val === null || val === undefined) return 'NULL';
  return `'${String(val).replace(/'/g, "''")}'`;
}

module.exports = {
  checkPostgresConnection,
  exportToPostgresSQL,
  PG_CONFIG
};
